#!/usr/bin/env python3
"""Render every generated artifact from its machine source.

    python tools/render_spec.py           # write
    python tools/render_spec.py --check   # exit 1 when a committed artifact differs (CI drift gate)

Sources -> artifacts:
    validator/validate.py (vocabulary, via import + AST) + validator/card-format.json  -> profiles/*.json
    grammar/RULES.md + grammar/cxtml.abnf + profiles/*.json + corpus expectations      -> spec/SPEC.md

No vocabulary list is written by hand anywhere in this repository: a hand-kept list drifts from the
enforcing code without a sound (upstream incident 2026-08-16), so lists are read from the code.
"""

from __future__ import annotations

import argparse
import ast
import importlib.util
import json
import os
import sys
from pathlib import Path

VERSION = "cXTML/1.0"
ROOT = Path(__file__).resolve().parent.parent
VAL = ROOT / "validator"
os.environ["XTML_CARD_FORMAT"] = str(VAL / "card-format.json")


def _load(path: Path, name: str):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _routing_literals(tree: ast.AST) -> tuple[dict, list]:
    """Enum sets written inside _routing_complaint (not importable: they are locals)."""
    fn = next(n for n in ast.walk(tree) if isinstance(n, ast.FunctionDef) and n.name == "_routing_complaint")
    enums, tiers = {}, []
    for node in ast.walk(fn):
        if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name):
            if node.targets[0].id == "enums":
                for k, v in zip(node.value.keys, node.value.values):
                    enums[ast.literal_eval(k)] = sorted(ast.literal_eval(v)) if isinstance(v, ast.Set) else None
            elif node.targets[0].id == "tiers":
                tiers = sorted(ast.literal_eval(node.value))
    return enums, tiers


def _strict_gap_profiles(tree: ast.AST) -> list:
    kw = next(n for n in ast.walk(tree) if isinstance(n, ast.keyword) and n.arg == "strict_gaps")
    return sorted(ast.literal_eval(kw.value.comparators[0]))


def profiles() -> dict[str, dict]:
    ref = _load(VAL / "validate.py", "cxtml_ref_render")
    cf = json.loads((VAL / "card-format.json").read_text(encoding="utf-8"))
    tree = ast.parse((VAL / "validate.py").read_text(encoding="utf-8"))
    enums, tiers = _routing_literals(tree)
    enums = {k: (v if v is not None else sorted(cf["phases"])) for k, v in enums.items()}
    gaps = _strict_gap_profiles(tree)
    markers = {"open": ref.OPEN, "sep": ref.SEP, "close": ref.CLOSE, "end_of_msg": ref.EOM}

    def common(p: str, depth: int) -> dict:
        return {
            "version": VERSION,
            "profile": p,
            "markers": markers,
            "elements": sorted(ref.VOCAB[p]),
            "end_of_msg_allowed": p in ref.EOM_ALLOWED,
            "text_directly_in_root": p not in gaps,
            "max_nest_depth": depth,
            "name_pattern": ref.NAME,
        }

    return {
        "kimi": common("kimi", ref.KIMI_NEST_DEPTH),
        "delegation": {
            **common("delegation", ref.MAX_NEST_DEPTH),
            "mandatory_sections": list(ref.MANDATORY),
            "v2_sections": sorted(ref.V2_SECTIONS),
            "loop_classes": list(ref.LOOP_CLASSES),
            "capability_keys": list(ref.CAPABILITY_KEYS),
            "context_budget_keys": list(ref.CONTEXT_BUDGET_KEYS),
            "seed_policies": list(ref.SEED_POLICIES),
            "verdict_marker": ref.VERDICT_MARKER,
            "routing": {
                "fields": cf["routing_fields"],
                "optional": cf["routing_optional"],
                "enums": enums,
                "previous_tier": tiers,
            },
        },
        "message": {
            **common("message", ref.MAX_NEST_DEPTH),
            "message": {k: v for k, v in ref.MSG.items() if k != "why"},
        },
        "doc": {**common("doc", ref.MAX_NEST_DEPTH), "roots": list(ref.DOC["roots"]), "closed_vocabulary": True},
    }


def _table(d: dict) -> str:
    rows = ["| key | value |", "|---|---|"]
    for k, v in d.items():
        if k in ("version", "profile", "markers"):
            continue
        shown = json.dumps(v, ensure_ascii=False) if not isinstance(v, str) else f"`{v}`"
        rows.append(f"| {k} | {shown.replace('|', chr(92) + '|')} |")
    return "\n".join(rows)


def spec(profs: dict[str, dict]) -> str:
    rules = (ROOT / "grammar" / "RULES.md").read_text(encoding="utf-8").split("\n", 1)[1].strip()
    abnf = (ROOT / "grammar" / "cxtml.abnf").read_text(encoding="utf-8").strip()
    out = [
        "<!-- GENERATED by tools/render_spec.py: do not edit. Edit grammar/, validator/ or card-format.json and re-render. -->",
        f"# {VERSION} specification",
        "",
        (
            "Part 1 is normative prose (grammar/RULES.md), part 2 the formal grammar (grammar/cxtml.abnf); "
            "part 3 is generated from the reference validator."
        ),
        "",
        "## 1. Rules",
        "",
        rules,
        "",
        "## 2. Formal grammar (ABNF, RFC 5234 + RFC 7405)",
        "",
        "```abnf",
        abnf,
        "```",
        "",
        "## 3. Profiles (generated from validator/validate.py + validator/card-format.json)",
        "",
    ]
    for name, p in profs.items():
        out += [f"### 3.{list(profs).index(name) + 1} {name}", "", _table(p), ""]
    return "\n".join(out)


def artifacts() -> dict[Path, str]:
    profs = profiles()
    arts = {
        ROOT / "profiles" / f"{n}.json": json.dumps(p, indent=1, ensure_ascii=False) + "\n" for n, p in profs.items()
    }
    arts[ROOT / "spec" / "SPEC.md"] = spec(profs)
    return arts


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="render generated artifacts")
    ap.add_argument("--check", action="store_true", help="fail on drift instead of writing")
    a = ap.parse_args(argv)
    drift = []
    for path, text in artifacts().items():
        data = text.encode("utf-8")
        if a.check:
            if not path.is_file() or path.read_bytes() != data:
                drift.append(path.relative_to(ROOT).as_posix())
        else:
            path.write_bytes(data)
    for d in drift:
        print(f"DRIFT {d}: committed file differs from its source; run tools/render_spec.py", file=sys.stderr)
    print("generated artifacts: " + ("DRIFT" if drift else ("in sync" if a.check else "written")))
    return 1 if drift else 0


if __name__ == "__main__":
    sys.exit(main())
